  let currentLanguage = readStoredLanguage();
  const listeners = new Set();

  function readStoredLanguage() {
    try {
      const stored = global.localStorage && global.localStorage.getItem(STORAGE_KEY);
      return supportedLanguages.includes(stored) ? stored : 'pt';
    } catch (error) {
      return 'pt';
    }
  }

  function interpolate(value, variables) {
    if (!variables) return value;
    return value.replace(/\{\{\s*([\w.]+)\s*\}\}/g, (match, key) => (
      Object.prototype.hasOwnProperty.call(variables, key) ? String(variables[key]) : match
    ));
  }

  function setDocumentLanguage() {
    if (global.document && global.document.documentElement) {
      global.document.documentElement.lang = metadata[currentLanguage].documentLanguage;
    }
  }

  function getLanguage() { return currentLanguage; }

  function setLanguage(language) {
    if (!supportedLanguages.includes(language)) return false;
    if (language === currentLanguage) {
      setDocumentLanguage();
      return false;
    }
    currentLanguage = language;
    try {
      if (global.localStorage) global.localStorage.setItem(STORAGE_KEY, currentLanguage);
    } catch (error) {
      // The app remains usable when storage is unavailable.
    }
    setDocumentLanguage();
    listeners.forEach((listener) => listener(currentLanguage));
    return true;
  }

  function t(key, variables, fallback) {
    const table = messages[currentLanguage] || messages.pt;
    const value = table[key] != null ? table[key] : messages.pt[key];
    return interpolate(value != null ? value : (fallback != null ? fallback : key), variables);
  }

  function localize(item, key) {
    if (!item || typeof item !== 'object') return item;
    if (currentLanguage === 'en') {
      if (key === 'pt' && typeof item.en === 'string') return item.en;
      const nested = item.en && typeof item.en === 'object' ? item.en[key] : null;
      const candidates = [nested, item[key + 'En'], item[key + '_en'], item[key + 'EN']];
      const translated = candidates.find((value) => value !== undefined && value !== null);
      if (translated !== undefined) return translated;
    }
    return item[key];
  }

  function subscribe(listener) {
    if (typeof listener !== 'function') return function () {};
    listeners.add(listener);
    return function unsubscribe() { listeners.delete(listener); };
  }

  function apply(root) {
    const scope = root || global.document;
    if (!scope || !scope.querySelectorAll) return;
    scope.querySelectorAll('[data-i18n]').forEach((element) => {
      element.textContent = t(element.dataset.i18n);
    });
    scope.querySelectorAll('[data-i18n-html]').forEach((element) => {
      element.innerHTML = t(element.dataset.i18nHtml);
    });
    scope.querySelectorAll('[data-i18n-aria-label]').forEach((element) => {
      element.setAttribute('aria-label', t(element.dataset.i18nAriaLabel));
    });
    scope.querySelectorAll('[data-i18n-title]').forEach((element) => {
      element.setAttribute('title', t(element.dataset.i18nTitle));
    });
    scope.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
      element.setAttribute('placeholder', t(element.dataset.i18nPlaceholder));
    });
    scope.querySelectorAll('[data-i18n-content]').forEach((element) => {
      element.setAttribute('content', t(element.dataset.i18nContent));
    });
  }

  setDocumentLanguage();

  global.KlarI18n = {
    STORAGE_KEY,
    languages: metadata,
    messages,
    getLanguage,
    setLanguage,
    t,
    localize,
    subscribe,
    apply
  };
